  const TABLES = { en: DICT, ja: JA, ko: KO };
  const RULESETS = { en: RULES, ja: RULES_JA, ko: RULES_KO };

  const SKIP = 'script,style,textarea,#frame,#authLang,#langSeg,.note-quote-text,.note-body,.mark-snippet,.search-hit p,.note-quote,#noteQuote,.reader-title strong,.book h3,.toc-item button>span:last-child';
  const ATTRS = ['placeholder', 'title', 'aria-label'];
  const ORIG_TEXT = new WeakMap();
  let lang = 'zh';
  let applying = false;

  function translateString(value) {
    if (lang === 'zh') return value;
    const dict = TABLES[lang];
    if (!dict) return value;
    const direct = dict[value];
    if (direct != null) return direct;
    for (const [re, replacement] of (RULESETS[lang] || [])) {
      if (re.test(value)) return value.replace(re, replacement);
    }
    return value;
  }

  function translateNodeText(node) {
    const raw = node.nodeValue;
    if (!raw) return;
    const match = raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match) return;
    const key = match[2];
    if (!key) return;
    const translated = translateString(key);
    if (translated === key) return;
    if (!ORIG_TEXT.has(node)) ORIG_TEXT.set(node, raw);
    node.nodeValue = match[1] + translated + match[3];
  }

  function translateAttributes(root) {
    const els = root.querySelectorAll ? [root, ...root.querySelectorAll('*')] : [];
    for (const el of els) {
      if (!(el instanceof Element)) continue;
      if (el.closest(SKIP)) continue;
      for (const name of ATTRS) {
        const value = el.getAttribute(name);
        if (!value) continue;
        const key = `i18n${name.replace(/-/g, '')}`;
        if (el.dataset[key] == null) el.dataset[key] = value;
        const translated = translateString(value);
        if (translated !== value) el.setAttribute(name, translated);
      }
    }
  }

  function translateTree(root) {
    if (lang === 'zh' || !root) return;
    applying = true;
    try {
      if (root.nodeType === Node.TEXT_NODE) {
        if (!root.parentElement || !root.parentElement.closest(SKIP)) translateNodeText(root);
        return;
      }
      if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
          if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
          if (node.parentElement && node.parentElement.closest(SKIP)) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        },
      });
      let node;
      while ((node = walker.nextNode())) translateNodeText(node);
      translateAttributes(root);
    } finally {
      applying = false;
    }
  }

  function restore(root) {
    applying = true;
    try {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
      let node;
      while ((node = walker.nextNode())) {
        if (ORIG_TEXT.has(node)) node.nodeValue = ORIG_TEXT.get(node);
      }
      const els = root.querySelectorAll ? root.querySelectorAll('*') : [];
      for (const el of els) {
        if (!(el instanceof Element)) continue;
        for (const name of ATTRS) {
          const key = `i18n${name.replace(/-/g, '')}`;
          if (el.dataset[key] != null) {
            el.setAttribute(name, el.dataset[key]);
            delete el.dataset[key];
          }
        }
      }
    } finally {
      applying = false;
    }
  }

  function setLang(next) {
    const target = ['en', 'ja', 'ko'].includes(next) ? next : 'zh';
    if (target === lang) {
      document.documentElement.lang = target === 'zh' ? 'zh-CN' : target;
      if (target !== 'zh') translateTree(document.body);
      return;
    }
    restore(document.body);
    lang = target;
    document.documentElement.lang = target === 'zh' ? 'zh-CN' : target;
    if (target !== 'zh') translateTree(document.body);
  }

  function startObserver() {
    let timer = 0;
    new MutationObserver((mutations) => {
      if (applying || lang === 'zh') return;
      clearTimeout(timer);
      timer = setTimeout(() => {
        for (const m of mutations) {
          for (const node of m.addedNodes) {
            if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) {
              translateTree(node);
            }
          }
        }
      }, 40);
    }).observe(document.body, { childList: true, subtree: true });
  }

